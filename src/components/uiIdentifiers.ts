export type UiIdentifierKey = keyof typeof uiIdentifiers;
export type UiIdentifierCode = (typeof uiIdentifiers)[UiIdentifierKey]["code"];
type ActiveAction = Extract<
  (typeof uiIdentifiers)[UiIdentifierKey],
  { kind: "action"; status: "active" }
>;
export type UiActionCode = ActiveAction["code"];
export type UiDialogCode = Extract<
  (typeof uiIdentifiers)[UiIdentifierKey],
  { kind: "dialog"; status: "active" }
>["code"];

export function validateUiIdentifierRegistry(
  registry: Readonly<Record<string, UiIdentifier>>,
  previousAllocations: Readonly<Record<string, string>> = {},
): void {
  const owners = new Map(
    Object.entries(previousAllocations).map(([key, code]) => [code, key]),
  );
  for (const [key, code] of Object.entries(previousAllocations)) {
    if (!registry[key] || registry[key].code !== code)
      throw Error(`Historical UI allocation must be retained: ${key}`);
  }
  const used = new Set<string>();
  for (const [key, entry] of Object.entries(registry)) {
    if (owners.has(entry.code) && owners.get(entry.code) !== key)
      throw Error(
        `Historical UI identifier cannot be reassigned: ${entry.code}`,
      );
    if (!/^[ADX]\d{2,}$/.test(entry.code))
      throw Error(`Invalid UI identifier: ${key}`);
    const prefix = { screen: "A", dialog: "D", action: "X" }[entry.kind];
    if (!entry.code.startsWith(prefix))
      throw Error(`UI identifier kind mismatch: ${key}`);
    if (used.has(entry.code))
      throw Error(`Duplicate UI identifier: ${entry.code}`);
    if (
      entry.status === "active" &&
      reservedUiCodesInThisStage.some((code) => code === entry.code)
    )
      throw Error(`Reserved UI identifier cannot be active: ${entry.code}`);
    used.add(entry.code);
    if (!entry.nameFa.trim() || !entry.effectFa.trim())
      throw Error(`Missing UI identifier meaning: ${key}`);
    if (entry.status === "active" && !entry.sites.length)
      throw Error(`Missing UI identifier usage sites: ${key}`);
  }
}
